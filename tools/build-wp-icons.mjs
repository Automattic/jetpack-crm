#!/usr/bin/env node
/**
 * Builds CRM's copy of the @wordpress/icons it uses, from tools/wp-icons.mjs.
 *
 *   npm run build:icons
 *   node tools/build-wp-icons.mjs --check   (fails if the committed files are out of date)
 *
 * Writes two files, both committed:
 *
 * - includes/jpcrm-wp-icons.php: the SVG paths, for jpcrm_wp_icon_svg().
 * - sass/_wp-icons.scss: draws each icon over the Semantic UI, Font Awesome and
 *   dashicons classes it replaces, as a CSS mask, so the old markup, including
 *   icons built in JS, shows @wordpress/icons without being rewritten.
 *
 * The SVGs come from the @wordpress/icons package in node_modules, so the
 * version in package.json is the version CRM ships.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import icons from './wp-icons.mjs';

const root = path.resolve( path.dirname( fileURLToPath( import.meta.url ) ), '..' );
const packageDir = path.join( root, 'node_modules/@wordpress/icons' );
const { version } = JSON.parse( fs.readFileSync( path.join( packageDir, 'package.json' ), 'utf8' ) );

// Where the CSS applies: CRM screens, including the CRM top bar, which WordPress
// prints above #wpbody-content.
const scope = '.jpcrm-admin #wpcontent';

const header = [
	`Generated by tools/build-wp-icons.mjs from @wordpress/icons ${ version }.`,
	"Don't edit by hand: change tools/wp-icons.mjs and run `npm run build:icons`.",
];

/**
 * Returns the markup inside an icon's <svg>, checking it's on the 24px grid.
 *
 * @param {string} name - Icon name in @wordpress/icons.
 * @return {string} The icon's paths.
 */
function iconPaths( name ) {
	const file = path.join( packageDir, 'src/library', `${ name }.svg` );
	if ( ! fs.existsSync( file ) ) {
		throw new Error( `@wordpress/icons ${ version } has no "${ name }" icon.` );
	}

	const svg = fs.readFileSync( file, 'utf8' );
	if ( ! /viewBox="0 0 24 24"/.test( svg ) ) {
		throw new Error( `"${ name }" isn't on the 24px grid.` );
	}

	return svg
		.replace( /^[\s\S]*?<svg[^>]*>/, '' )
		.replace( /<\/svg>[\s\S]*$/, '' )
		.replace( /\s*\n\s*/g, '' )
		.trim();
}

// For a CSS url(): no double quotes, and escape the characters url() can't hold.
const dataUri = paths =>
	'data:image/svg+xml,' +
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">${ paths }</svg>`
		.replace( /"/g, "'" )
		.replace( /%/g, '%25' )
		.replace( /#/g, '%23' )
		.replace( /</g, '%3C' )
		.replace( />/g, '%3E' );

const names = Object.keys( icons ).sort();
const paths = Object.fromEntries( names.map( name => [ name, iconPaths( name ) ] ) );

// PHP: name => paths, with the arrows aligned the way phpcs wants.
const keyWidth = Math.max( ...names.map( name => name.length ) );
const php = [
	'<?php',
	'/**',
	...header.map( line => ` * ${ line }` ),
	' *',
	' * @package automattic/jetpack-crm',
	' */',
	'',
	'return array(',
	...names.map(
		name =>
			`\t'${ name }'${ ' '.repeat( keyWidth - name.length ) } => '${ paths[ name ].replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }',`
	),
	');',
	'',
].join( '\n' );

// SCSS: one rule that swaps every mapped icon's glyph for a mask, then each icon's image.
const mapped = names.filter( name => icons[ name ].length );
const allSelectors = mapped.flatMap( name => icons[ name ] );
const scss = [
	...header.map( line => `// ${ line }` ),
	'',
	`${ scope } {`,
	'',
	'\t// The icon-font glyph goes, and the icon is painted in the text color through a',
	'\t// mask. @wordpress/icons leave space around the artwork on their 24px grid, so the',
	"\t// box is 1.5em to draw it at the font glyph's size, and the negative margin keeps",
	'\t// the layout the glyph had. :where() keeps this at the scope\'s specificity, which',
	'\t// already beats the icon fonts, so the rules below can adjust it.',
	`\t:where(${ allSelectors.join( ', ' ) })::before {`,
	'\t\tcontent: "";',
	'\t\tdisplay: inline-block;',
	'\t\twidth: 1.5em;',
	'\t\theight: 1.5em;',
	'\t\tmargin: -0.25em;',
	'\t\tvertical-align: -0.125em;',
	'\t\t-webkit-mask: var(--jpcrm-wp-icon) center / contain no-repeat;',
	'\t\tmask: var(--jpcrm-wp-icon) center / contain no-repeat;',
	'',
	'\t\t// Semantic UI clears icon backgrounds with !important.',
	'\t\tbackground: currentColor !important;',
	'\t}',
	'',
	'\t// Semantic UI centers the glyph absolutely inside input and labeled button icons.',
	`\t:where(${ allSelectors.join( ', ' ) }):is(.ui.icon.input > i.icon, .ui.labeled.icon.button > .icon, .ui.labeled.icon.buttons > .button > .icon)::before {`,
	'\t\tposition: absolute;',
	'\t\ttop: 50%;',
	'\t\tleft: 50%;',
	'\t\tmargin: -0.75em 0 0 -0.75em;',
	'\t\ttransform: none;',
	'\t}',
	...mapped.flatMap( name => [
		'',
		`\t// ${ name }`,
		`\t${ icons[ name ].join( ',\n\t' ) } {`,
		`\t\t--jpcrm-wp-icon: url("${ dataUri( paths[ name ] ) }");`,
		'\t}',
	] ),
	'}',
	'',
].join( '\n' );

const outputs = {
	'includes/jpcrm-wp-icons.php': php,
	'sass/_wp-icons.scss': scss,
};

if ( process.argv.includes( '--check' ) ) {
	const stale = Object.keys( outputs ).filter(
		file => ! fs.existsSync( path.join( root, file ) ) || fs.readFileSync( path.join( root, file ), 'utf8' ) !== outputs[ file ]
	);
	if ( stale.length ) {
		console.error( `Out of date: ${ stale.join( ', ' ) }. Run \`npm run build:icons\`.` );
		process.exit( 1 );
	}
	console.log( 'Icon files are up to date.' );
} else {
	for ( const [ file, contents ] of Object.entries( outputs ) ) {
		fs.writeFileSync( path.join( root, file ), contents );
	}
	console.log( `Wrote ${ names.length } icons (${ allSelectors.length } old icon selectors) from @wordpress/icons ${ version }.` );
}
