#!/usr/bin/env node
/**
 * Builds CRM's copy of the icons it uses, from tools/wp-icons.mjs.
 *
 *   npm run build:icons
 *   node tools/build-wp-icons.mjs --check   (fails if the committed files are out of date)
 *
 * Writes three files, all committed:
 *
 * - includes/jpcrm-wp-icons.php: the SVG markup, for jpcrm_wp_icon_svg().
 * - sass/_wp-icons-data.scss: the icons as data URIs, and a wp-icon() mixin for
 *   stylesheets that draw an icon themselves. It prints no CSS on its own.
 * - sass/_wp-icons.scss: draws each icon over the Semantic UI, Font Awesome and
 *   dashicons classes it replaces, as a CSS mask, so the old markup, including
 *   icons built in JS, shows the new icons without being rewritten.
 *
 * The SVGs come from @wordpress/icons and social-logos in node_modules, so the
 * versions in package.json are what CRM ships, and from tools/icons/.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import wordpressIcons, { customIcons, socialLogos } from './wp-icons.mjs';

const root = path.resolve( path.dirname( fileURLToPath( import.meta.url ) ), '..' );
const packageVersion = name =>
	JSON.parse( fs.readFileSync( path.join( root, 'node_modules', name, 'package.json' ), 'utf8' ) ).version;

// Where the CSS applies: CRM screens, including the CRM top bar, which WordPress
// prints above #wpbody-content.
const scope = '.jpcrm-admin #wpcontent';

const header = [
	`Generated by tools/build-wp-icons.mjs from @wordpress/icons ${ packageVersion( '@wordpress/icons' ) }, social-logos ${ packageVersion( 'social-logos' ) } and tools/icons.`,
	"Don't edit by hand: change tools/wp-icons.mjs and run `npm run build:icons`.",
];

/**
 * Returns the markup inside an <svg>, checking it's on the 24px grid.
 *
 * @param {string} svg   - The SVG.
 * @param {string} label - What it is, for errors.
 * @return {string} The SVG's contents.
 */
function svgContents( svg, label ) {
	if ( ! /viewBox="0 0 24 24"/.test( svg ) ) {
		throw new Error( `${ label } isn't on the 24px grid.` );
	}

	return svg
		.replace( /^[\s\S]*?<svg[^>]*>/, '' )
		.replace( /<\/svg>[\s\S]*$/, '' )
		.replace( /<title>[\s\S]*?<\/title>/g, '' )
		.replace( /\s*\n\s*/g, '' )
		.trim();
}

const readWordPressIcon = name => {
	const file = path.join( root, 'node_modules/@wordpress/icons/src/library', `${ name }.svg` );
	if ( ! fs.existsSync( file ) ) {
		throw new Error( `@wordpress/icons has no "${ name }" icon.` );
	}
	return svgContents( fs.readFileSync( file, 'utf8' ), `@wordpress/icons "${ name }"` );
};

const socialSprite = fs.readFileSync( path.join( root, 'node_modules/social-logos/build/svg-sprite/social-logos.svg' ), 'utf8' );
const readSocialLogo = name => {
	const symbol = socialSprite.match( new RegExp( `<symbol id="${ name }" viewBox="([^"]+)">([\\s\\S]*?)</symbol>` ) );
	if ( ! symbol ) {
		throw new Error( `social-logos has no "${ name }" logo.` );
	}
	return svgContents( `<svg viewBox="${ symbol[ 1 ] }">${ symbol[ 2 ] }</svg>`, `social-logos "${ name }"` );
};

const readCustomIcon = name => {
	const file = path.join( root, 'tools/icons', `${ name }.svg` );
	if ( ! fs.existsSync( file ) ) {
		throw new Error( `tools/icons/${ name }.svg doesn't exist.` );
	}
	return svgContents( fs.readFileSync( file, 'utf8' ), `tools/icons/${ name }.svg` );
};

// Every icon: name => { contents, replaces, color }.
const icons = {};
for ( const [ list, read ] of [
	[ wordpressIcons, readWordPressIcon ],
	[ socialLogos, readSocialLogo ],
	[ customIcons, readCustomIcon ],
] ) {
	for ( const [ name, value ] of Object.entries( list ) ) {
		if ( icons[ name ] ) {
			throw new Error( `"${ name }" is listed twice.` );
		}
		const { replaces = [], color = null } = Array.isArray( value ) ? { replaces: value } : value;
		icons[ name ] = { contents: read( name ), replaces, color };
	}
}

// For a CSS url(): no double quotes, and escape the characters url() can't hold.
// stroke="currentColor" has no color inside an image, so draw it black for the mask.
const dataUri = contents =>
	'data:image/svg+xml,' +
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">${ contents.replace( /currentColor/g, '#000' ) }</svg>`
		.replace( /"/g, "'" )
		.replace( /%/g, '%25' )
		.replace( /#/g, '%23' )
		.replace( /</g, '%3C' )
		.replace( />/g, '%3E' );

const names = Object.keys( icons ).sort();

// PHP: name => SVG contents, with the arrows aligned the way phpcs wants. Brand
// marks are filled with their color; the rest take the text color.
const keyWidth = Math.max( ...names.map( name => name.length ) );
const phpContents = name => {
	const { contents, color } = icons[ name ];
	return color ? `<g fill="${ color }">${ contents }</g>` : contents;
};
const php = [
	'<?php',
	'/**',
	...header.map( line => ` * ${ line }` ),
	' *',
	' * @package automattic/jetpack-crm',
	' */',
	'',
	'return array(',
	...names.map(
		name =>
			`\t'${ name }'${ ' '.repeat( keyWidth - name.length ) } => '${ phpContents( name ).replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }',`
	),
	');',
	'',
].join( '\n' );

// Sass data: the data URIs and the mixin. Prints no CSS.
const data = [
	...header.map( line => `// ${ line }` ),
	'',
	'@use "sass:map";',
	'',
	'$wp-icons: (',
	...names.map( name => `\t"${ name }": url("${ dataUri( icons[ name ].contents ) }"),` ),
	');',
	'',
	'// Draws an icon on a ::before or ::after, in the text color. The icons leave space',
	'// around the artwork on their 24px grid, so the box is 1.5em to draw it at a font',
	"// glyph's size, and the negative margin keeps the layout a glyph would have.",
	'@mixin wp-icon( $name ) {',
	'\t@if not map.has-key( $wp-icons, $name ) {',
	'\t\t@error "No icon called #{$name}. Add it to tools/wp-icons.mjs and run npm run build:icons.";',
	'\t}',
	'',
	'\tcontent: "";',
	'\tdisplay: inline-block;',
	'\twidth: 1.5em;',
	'\theight: 1.5em;',
	'\tmargin: -0.25em;',
	'\tvertical-align: -0.125em;',
	'\t-webkit-mask: map.get( $wp-icons, $name ) center / contain no-repeat;',
	'\tmask: map.get( $wp-icons, $name ) center / contain no-repeat;',
	'\tbackground: currentColor;',
	'}',
	'',
].join( '\n' );

// Sass rules: one rule that swaps every mapped icon's glyph for a mask, then each icon's image.
const mapped = names.filter( name => icons[ name ].replaces.length );
const allSelectors = mapped.flatMap( name => icons[ name ].replaces );
const scss = [
	...header.map( line => `// ${ line }` ),
	'',
	'@use "sass:map";',
	'@use "wp-icons-data" as data;',
	'',
	`${ scope } {`,
	'',
	'\t// The icon-font glyph goes, and the icon is painted through a mask in the text',
	"\t// color. :where() keeps this at the scope's specificity, which already beats the",
	'\t// icon fonts, so the rules below can adjust it.',
	`\t:where(${ allSelectors.join( ', ' ) })::before {`,
	'\t\tcontent: "";',
	'\t\tdisplay: inline-block;',
	'\t\twidth: 1.5em;',
	'\t\theight: 1.5em;',
	'\t\tmargin: -0.25em;',
	'\t\tvertical-align: -0.125em;',
	'\t\t-webkit-mask: var(--jpcrm-wp-icon) center / contain no-repeat;',
	'\t\tmask: var(--jpcrm-wp-icon) center / contain no-repeat;',
	'',
	'\t\t// Semantic UI clears icon backgrounds with !important.',
	'\t\tbackground: currentColor !important;',
	'\t}',
	'',
	'\t// Semantic UI centers the glyph absolutely inside input and labeled button icons.',
	`\t:where(${ allSelectors.join( ', ' ) }):is(.ui.icon.input > i.icon, .ui.labeled.icon.button > .icon, .ui.labeled.icon.buttons > .button > .icon)::before {`,
	'\t\tposition: absolute;',
	'\t\ttop: 50%;',
	'\t\tleft: 50%;',
	'\t\tmargin: -0.75em 0 0 -0.75em;',
	'\t\ttransform: none;',
	'\t}',
	...mapped.flatMap( name => [
		'',
		`\t// ${ name }`,
		`\t${ icons[ name ].replaces.join( ',\n\t' ) } {`,
		`\t\t--jpcrm-wp-icon: #{ map.get( data.$wp-icons, "${ name }" ) };`,
		...( icons[ name ].color ? [ `\t\tcolor: ${ icons[ name ].color };` ] : [] ),
		'\t}',
	] ),
	'}',
	'',
].join( '\n' );

const outputs = {
	'includes/jpcrm-wp-icons.php': php,
	'sass/_wp-icons-data.scss': data,
	'sass/_wp-icons.scss': scss,
};

if ( process.argv.includes( '--check' ) ) {
	const stale = Object.keys( outputs ).filter(
		file => ! fs.existsSync( path.join( root, file ) ) || fs.readFileSync( path.join( root, file ), 'utf8' ) !== outputs[ file ]
	);
	if ( stale.length ) {
		console.error( `Out of date: ${ stale.join( ', ' ) }. Run \`npm run build:icons\`.` );
		process.exit( 1 );
	}
	console.log( 'Icon files are up to date.' );
} else {
	for ( const [ file, contents ] of Object.entries( outputs ) ) {
		fs.writeFileSync( path.join( root, file ), contents );
	}
	console.log( `Wrote ${ names.length } icons (${ allSelectors.length } old icon selectors).` );
}
